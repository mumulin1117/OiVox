import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { discoveryExperienceContent } from '../data/discoveryExperienceContent'

describe('single-card voice discovery contract', () => {
  const component = readFileSync(resolve(process.cwd(), 'src/components/VoiceDiscoveryScreen.vue'), 'utf8')
  const css = readFileSync(resolve(process.cwd(), 'src/styles.css'), 'utf8')

  it('opens on the requested stable user and only exposes public profile fields', () => {
    expect(component).toContain('props.initialUserId')
    expect(component).toContain('toPublicSocialProfile')
    expect(component).toContain('createDiscoveryStore')
    expect(component).toContain('currentProfile.avatarAsset')
    expect(component).toContain('currentProfile.voiceClip')
    expect(component).toContain('currentProfile.voiceClip.transcript')
    expect(component).toContain('currentProfile.countryLabel')
    expect(component).toContain('currentProfile.flagAsset')
  })

  it('uses the Blue Lake local icon layers and opens history plus the filter bottom sheet', () => {
    const filterSheet = readFileSync(resolve(process.cwd(), 'src/components/DiscoveryFilterSheet.vue'), 'utf8')
    expect(component).toContain("import historyIcon from '../assets/icons/discovery-history.svg'")
    expect(component).toContain("import filterIcon from '../assets/icons/discovery-filter.svg'")
    expect(component).toContain("@click=\"openPanel('history')\"")
    expect(component).toContain('@click="openFilter"')
    expect(component).toContain('<TranslationHistoryScreen')
    expect(component).toContain('<DiscoveryFilterSheet')
    expect(component).toContain('discoveryStore.setFilters')
    expect(filterSheet).toContain('copy.purchaseOnlyNote')
    expect(filterSheet).toContain('class="voice-filter-drag-zone"')
    expect(filterSheet).toContain('@pointerdown="beginDrag"')
    expect(filterSheet).toContain('@pointercancel="finishDrag($event, true)"')
    expect(filterSheet).toContain('@lostpointercapture="finishDrag($event, true)"')
    expect(filterSheet).toContain("'--filter-drag-offset': `${dragOffset}px`")
    expect(component).not.toContain('<LanguageScreen')
    expect(css).toContain('.voice-filter-sheet')
    expect(css).toContain('.voice-filter-scope-note')
    expect(css).toContain('.voice-filter-sheet.is-dragging')
    expect(css).toContain('.voice-filter-drag-zone')
    expect(css).toContain('height: min(76dvh,760px)')
    expect(css).toContain('transform: translateY(var(--filter-drag-offset,0px))')
    expect(css).toContain('border-radius: 28px 28px 0 0')
  })

  it('keeps likes and friend requests as separate idempotent actions', () => {
    expect(component).toContain("socialStore.setLiked")
    expect(component).toContain('@click="toggleLike"')
    expect(component).toContain('socialStore.sendFriendRequest')
    expect(component).toContain("operationID('discovery-request')")
    expect(component).toContain("relationship.value?.friendshipStatus === 'pending_out'")
    expect(component).toContain("['friends', 'pending_out'].includes(relationship.value?.friendshipStatus)")
    expect(component).toContain(':disabled="addDisabled || decisionBusy"')
    expect(component).not.toContain("friendshipStatus: 'friends'")
  })

  it('tracks remaining opportunities, exhausts once, and exchanges 50 coins for five cards', () => {
    expect(component).toContain('remainingCount')
    expect(component).toContain('discoveryStore.decide')
    expect(component).toContain('voice-discovery-exhausted')
    expect(component).toContain('walletStore.exchangeDiscoveryCards')
    expect(component).toContain("openCoinStore('card-pack')")
    expect(component).toContain('@purchase-complete="handleCoinPurchaseComplete"')
    expect(component).toContain('@click="toggleLike"')
    expect(component).not.toContain('@click="decide(\'like\')"')
  })

  it('reopens a processed home card in read-only review mode without restoring or repeating its decision', () => {
    expect(component).toContain('discoverySnapshot.value.allocatedUserIDs.includes(currentUserID.value)')
    expect(component).toContain('const currentDecision = computed(')
    expect(component).toContain('const isReviewMode = computed(')
    expect(component).not.toContain('voice-discovery-review-note')
    expect(component).toContain('copy.freeToday.replace')
    expect(component).toContain('skipButtonIcon')
    expect(component).toContain('decisionBusy.value || exhausted.value || isReviewMode.value')
    expect(component).toContain(':disabled="decisionBusy || exhausted || isReviewMode"')
    expect(component).toContain('v-if="nextProfile && !isReviewMode"')
  })

  it('keeps the skip button touch target square while scaling the supplied artwork to the Add button height', () => {
    expect(css).toContain('.voice-discovery-pass { position: relative; z-index: 1; width: 56px; aspect-ratio: 1; overflow: visible; background: transparent; }')
    expect(css).toContain('.voice-discovery-pass img { width: 88px; height: 88px; max-width: none; max-height: none; object-fit: contain; pointer-events: none; transform: translateY(7px); }')
    expect(css).toContain('.voice-discovery-pass img { width: 82px; height: 82px; transform: translateY(6px); }')
    expect(css).toContain('.voice-discovery-actions { position: relative; z-index: 6; flex: none; display: grid; grid-template-columns: 56px 76px minmax(0,1fr); grid-template-rows: 56px 24px;')
    expect(css).toContain('.voice-discovery-pass, .voice-discovery-like { grid-row: 1; align-self: center; }')
  })

  it('matches the Blue Lake version-1 coin confirmation sheet without changing the exchange transaction', () => {
    expect(component).toContain("'is-card-pack-sheet': cardPackModal === 'confirm'")
    expect(component).toContain('class="voice-discovery-card-pack-art"><img :src="coinIcon"')
    expect(component).toContain('class="voice-discovery-card-pack-breakdown"')
    expect(component).toContain('class="voice-discovery-card-pack-actions"')
    expect(component).toContain(':aria-busy="cardPackBusy"')
    expect(component).toContain('@keydown.esc.stop="closeCardPackModal"')
    expect(component).toContain("@pointerdown=\"beginCoinSheetDrag($event, 'card-pack')\"")
    expect(component).toContain('@pointercancel="finishCoinSheetDrag($event, true)"')
    expect(component).toContain('@lostpointercapture="finishCoinSheetDrag($event, true)"')
    expect(component).toContain("'--coin-sheet-drag-offset': `${coinSheetKind === 'card-pack' ? coinSheetDragOffset : 0}px`")
    expect(css).toContain('background: rgba(27,28,46,.42)')
    expect(css).toContain('border-radius: 28px 28px 0 0')
    expect(css).toContain('box-shadow: 0 -18px 50px rgba(40,86,111,.24)')
    expect(css).toContain('.voice-discovery-card-pack-dialog.is-dragging')
    expect(css).toContain('.voice-discovery-card-pack-drag-zone')
    expect(css).toContain('height: min(387px,calc(var(--app-height) - max(20px,env(safe-area-inset-top))))')
    expect(css).toContain('width: 54px; height: 54px')
    expect(css).toContain('height: 110px')
    expect(css).toContain('grid-template-columns: 86px minmax(0,1fr)')
    expect(component).toContain('walletStore.exchangeDiscoveryCards')
  })

  it('opens the profile and uses explicit coin-confirmed translation and StoreKit screens', () => {
    expect(component).toContain("emit('open-profile', currentProfile.value.id)")
    expect(component).toContain('class="voice-discovery-profile"')
    expect(component).toContain('data-discovery-swipe-ignore')
    expect(component).toContain('@click.stop="openProfile"')
    expect(css).toContain('.voice-discovery-profile { width: 100%; min-height: 44px;')
    expect(component.indexOf('voice-discovery-match')).toBeLessThan(component.indexOf('voice-discovery-profile'))
    expect(component.indexOf('voice-discovery-profile')).toBeLessThan(component.indexOf('voice-discovery-actions'))
    const supportedLocales = ['en', 'ar', 'he', 'tr', 'fr', 'de', 'ja', 'ko']
    supportedLocales.forEach((locale) => {
      expect(discoveryExperienceContent(locale).viewProfile).toBeTruthy()
    })
    expect(component).toContain("translationModal.value = walletBalance.value < 5 ? 'insufficient' : 'confirm'")
    expect(component).toContain("translationModal.value = 'insufficient'")
    expect(component).toContain("import insufficientWarningArt from '../assets/slices/coin-insufficient-warning@2x.png'")
    expect(component).toContain('class="voice-discovery-coin-shortfall"')
    expect(component).toContain('class="voice-discovery-coin-packs"')
    expect(component).toContain('role="radiogroup"')
    expect(component).toContain(':aria-checked="selectedInsufficientProductID === pack.productID"')
    expect(component).toContain('@click="selectInsufficientProduct(pack.productID)"')
    expect(component).toContain('@click="buySelectedInsufficientProduct"')
    expect(component).toContain('purchaseCoinProduct({')
    expect(component).toContain('loadCoinProductPrices')
    expect(component).toContain('{{ commerceCopy.getCoins }}')
    expect(component).toContain('{{ insufficientPurchaseNote }}')
    expect(component).not.toContain('voice-discovery-coin-store-status')
    expect(component).toContain('Math.max(0, 5 - walletBalance)')
    expect(component).toContain('walletStore.spend({ amount: 5')
    expect(component).toContain('<CoinStoreScreen')
    expect(component).toContain('translationHistoryStore.add')
    expect(component).toContain('getDiscoveryVoiceTranslation')
    expect(component).toContain('originalText: clip.transcript')
    expect(css).toContain('.voice-discovery-modal.is-coin-spend-sheet')
    expect(component).toContain("@pointerdown=\"beginCoinSheetDrag($event, 'translation')\"")
    expect(component).toContain('@click.self="closeTranslationModal"')
    expect(css).toContain('.voice-discovery-coin-dialog.is-dragging')
    expect(css).toContain('.voice-discovery-coin-drag-zone')
    expect(css).toContain('grid-template-columns: 86px minmax(0,1fr)')
    expect(css).toContain('background: rgba(27,28,46,.42)')
    expect(css).toContain('.voice-discovery-coin-dialog.is-confirm { height: min(387px')
    expect(css).toContain('.voice-discovery-coin-dialog.is-insufficient { height: min(379px')
    expect(css).toContain('width: 40px; height: 5px')
    expect(css).toContain('background: rgba(255,255,255,1)')
    expect(component).not.toContain('skipsTranslationConfirmation')
    expect(component).not.toContain('rememberTranslationChoice')
    expect(component).not.toContain('purchaseFiveMore(`discovery-pack-after-')
  })

  it('supports accessible switching, pointer cancellation, and audio cleanup', () => {
    expect(component).toMatch(/class="voice-discovery-entry-surface"[\s\S]*@pointerdown="beginDrag"/)
    expect(component).toContain('@click.capture="guardClickAfterSwipe"')
    expect(component).toContain('@pointercancel="cancelDrag"')
    expect(component).toContain('@lostpointercapture="cancelDrag"')
    expect(component).toContain('localX <= edgeGuard')
    expect(component).toContain('event.stopImmediatePropagation?.()')
    expect(component).not.toMatch(/voice-discovery-card-current[^>]+@pointerdown="beginDrag"/)
    expect(component).toContain('voicePlaybackService.stop()')
    expect(component).toContain("document.removeEventListener('visibilitychange', stopHiddenAudio)")
    expect(css).toMatch(/\.voice-discovery-entry-surface \{[^}]*touch-action: pan-y/)
    expect(css).toContain('.voice-discovery-player.active .voice-discovery-wave i')
    expect(css).toContain('.voice-discovery-player.paused .voice-discovery-wave i')
    expect(component).toContain('class="voice-discovery-player"')
    expect(component).toContain('data-discovery-swipe-ignore')
    expect(component).toContain('@pointerdown.stop @click.stop="toggleVoice"')
    expect(component).toContain('@click.stop="toggleVoice"')
  })

  it('reveals the Blue Lake card surface from its center without exposing controls early', () => {
    expect(component).toContain('animateEntry: { type: Boolean, default: false }')
    expect(component).toContain("const entryPhase = ref(props.animateEntry ? 'pending' : 'ready')")
    expect(component).toContain("clipPath: 'circle(0% at 50% 43%)'")
    expect(component).toContain("clipPath: 'circle(150% at 50% 43%)'")
    expect(component).toContain(':inert="entryPhase !== \'ready\' || Boolean(')
    expect(component).toContain("window.matchMedia('(prefers-reduced-motion: reduce)')")
    expect(component).toContain("window.visualViewport?.addEventListener('resize', handleViewportChange)")
    expect(component).toContain('entryAnimation?.cancel()')
    expect(css).toContain('.voice-discovery-screen.is-entry-pending .voice-discovery-entry-surface')
  })
})
